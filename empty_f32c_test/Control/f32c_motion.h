#ifndef __F32C_MOTION_H
#define __F32C_MOTION_H
#include "board.h"

/* ============================================================
 * F32C 云台"回零 + 0°~180° 往返"运动控制
 *
 * 分工：
 *   - 本模块只做数学：把目标角度按梯形（T 型）速度曲线一点点推出去，
 *     并且判断驱动板有没有真的到位。不碰串口。
 *   - 曲线在 TIMG0 中断里跑（每 6.667ms 一拍，见 control.c），主循环只负责
 *     把 F32C_Setpoint_X10 这个"当前应该在哪"发出去（见 empty.c）。
 *     放中断里跑的好处：主循环刷 OLED 那十几毫秒不会把曲线卡住。
 *
 * 为什么要 MCU 侧规划：手册 P7 说"需要高频率的发送改变目标位置，建议选择
 * 直通模式"，本工程就是 150Hz 连续下发；但直通模式下直接把 0 跳到 1800
 * 发过去，驱动板位置环会以"运行速度"上限猛冲，到位时容易冲过头来回晃。
 * 所以由 MCU 把目标点按加速度铺开，驱动板只需要跟一个每拍只动几度的
 * 移动目标，既快又不会过冲；加减速也能自己调。
 * ============================================================ */

/* ---------- 行程 ---------- */
#define F32C_HOME_X10        0        /* 回零点：0.0° */
#define F32C_GOAL_X10        1800     /* 往返另一端：180.0° */

/* ---------- 速度与加减速（单位都是 0.1°）----------
 * 180° 这个行程跑出来是"三角形"曲线（加速段 90° + 减速段 90°，中间没有匀速
 * 段），时间 t = 2√(d/a)、峰值速度 √(d·a)。所以想快不能只调一个：
 *   只加 ACC → 峰值会顶到 VMAX 被削平，快到一定程度就再也上不去了；
 *   必须 VMAX 和 ACC 一起加。
 * 下面这组对应"0°→180° 单程约 0.25 秒"、峰值 1440°/s（=240RPM）。
 * 想再快就整行换档（整数算法离线复刻跑过，各档落点都精确 1800、无过冲）：
 *   VMAX 14400 / ACC 115200 →  37 拍 0.247s，峰值 240RPM   ← 当前
 *   VMAX 18000 / ACC 180000 →  31 拍 0.207s，峰值 300RPM
 *   VMAX 22800 / ACC 288000 →  24 拍 0.160s，峰值 380RPM
 *   VMAX 28800 / ACC 460800 →  18 拍 0.120s，峰值 480RPM
 * ⚠️ 这些"拍数"是按一拍 6.667ms 数出来的。改 SysConfig 的周期就必须重算一遍
 *    —— 物理量（°/s、°/s²）不变，但落在整数拍上会差几个 tick。
 * 真正的上限不在代码，在电机扭矩和机械结构：上到某一档会开始丢步、
 * 啸叫或者整机发抖，那就是到头了。想更平顺就把 ACC 往下调。 */
#define F32C_VMAX_X10S       14400
#define F32C_ACC_X10S2       115200

/* ---------- 回零用一组较慢的参数，避免上电就猛冲 ---------- */
#define F32C_HOME_VMAX_X10S  3600
#define F32C_HOME_ACC_X10S2  28800

/* ---------- 回零完成后要不要自动开始往返 ----------
 *   1 = 回零完立刻开始 0°↔180° 往返（演示用）
 *   0 = 回零完停在 0° 不动（状态进 F32C_ST_HOLD，驱动板位置环把电机锁在
 *       零点上）。想先摆好机构、或者只想看它回零落点，就用 0。 */
#define F32C_AUTO_RUN        1

/* ---------- 时序 ----------
 * 一拍多长必须和 SysConfig 里 TIMER_0 的 Desired Timer Period 一致。那里填的
 * 是 6.667 ms（1.25MHz 计数 → LOAD 8333 → 实际 6.6672ms，149.99Hz），不是整数
 * 毫秒，所以这里的单位是微秒 —— 下面的 Q8 换算全拿它当因子，用整数 ms 会把
 * 一拍算成 6 或 7ms，速度和加速度就整体偏了。改 SysConfig 的周期必须同步改这里。 */
#define F32C_TICK_US         6667     /* 一拍多少微秒（149.99Hz）*/

/* 毫秒 → 拍数（向上取整）。DWELL / 兜底超时这些是按"毫秒"想的，但一拍不是
 * 整数毫秒，直接 (ms*1000)/F32C_TICK_US 截断会少算一拍。 */
#define F32C_MS_TO_TICKS(ms) (((ms) * 1000 + F32C_TICK_US - 1) / F32C_TICK_US)

#define F32C_DWELL_MS        80       /* 两端各停留多久。停留越长越"一顿一顿"；
                                       * 想让往返看着像连续摆动就往下调，
                                       * 想看清两个端点停稳就往上调。 */
#define F32C_ARRIVE_X10      15       /* 到位判据：反馈角度离终点 1.5° 以内 */
#define F32C_ARRIVE_TICKS    6        /* 且要连续 6 拍（40ms）都在判据内 */
#define F32C_ARRIVE_TIMEOUT_MS 400    /* 兜底：曲线走完 400ms 还没进到位判据也
                                       * 往下走。这个值不能大 —— 万一电机因为
                                       * 负载停偏了一点、没进判据，两端就会各
                                       * 僵住这么久，看起来像"走一下卡两秒"。 */

/* 下发给驱动板的"位置模式运行速度"上限（RPM，手册 4.2.3 范围 0~1000）。
 * 它只是安全上限：正常跟随 MCU 曲线时根本到不了，只有被外力顶开、
 * 误差突然拉大时才会起作用。要真正把电机限慢，改这个值。
 * ⚠️ 但它同时会削平曲线峰值 —— 曲线峰值超过这个数，那一段就会变成匀速，
 * 加减速白调。所以它必须比上面那档的峰值留出余量（当前峰值 240RPM）。 */
#define F32C_RUN_SPEED_RPM   500

typedef enum {
    F32C_ST_WAIT = 0,   /* 上电还没开始（等握手/识别电机）*/
    F32C_ST_HOMING,     /* 正在回零 */
    F32C_ST_DWELL,      /* 到端点了，停留中 */
    F32C_ST_MOVING,     /* 正在往返 */
    F32C_ST_HOLD        /* 停住（按键暂停，或手动回零后停住）*/
} F32C_State_t;

extern volatile F32C_State_t F32C_State;
extern volatile int  F32C_Setpoint_X10;   /* 曲线当前点＝这一刻该发给驱动板的角度 */
extern volatile int  F32C_Goal_X10;       /* 本段的终点 */
extern volatile u8   F32C_MotorID;        /* 1 / 2；0 = 没识别出来 */
extern volatile u32  F32C_CycleCount;     /* 完成的往返趟数（回到 0° 算一趟）*/
extern volatile u32  F32C_TickCount;      /* 上电以来经过的拍数，×6.667ms 就是毫秒 */

/* 上电/握手完成后调一次：motor_id 为识别到的 ID（0=没识别出来），
 * start_x10 为电机当前机械角度，曲线从这里起步，不会一上电就跳。 */
void F32C_Motion_Begin(u8 motor_id, int start_x10);

/* 每 6.667ms 调一次（放在 TIMG0 中断里）。 */
void F32C_Motion_Tick(void);

/* 主循环每收到一帧机械角度反馈就调一次，到位判据用它。 */
void F32C_Motion_Feedback(int fb_x10);

void F32C_Motion_ToggleRun(void);   /* 短按：暂停 / 继续往返 */
void F32C_Motion_GoHome(void);      /* 长按：回零并停住 */

const char *F32C_StateText(void);

#endif
